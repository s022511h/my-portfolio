  BuildingIcon,
  ScissorsIcon,
  BarChart3Icon,
  AlertCircleIcon,
  WrenchIcon,
  CheckIcon,
  TrendingUpIcon,
  TrendingDownIcon,
  ChevronLeftIcon,
  ChevronRightIcon,
  PlayIcon,
  XIcon,
  ArrowRightIcon
} from 'lucide-vue-next'

export default {
  name: 'ResultsPage',
  
  components: {
    BuildingIcon,
    ScissorsIcon,
    BarChart3Icon,
    AlertCircleIcon,
    WrenchIcon,
    CheckIcon,
    TrendingUpIcon,
    TrendingDownIcon,
    ChevronLeftIcon,
    ChevronRightIcon,
    PlayIcon,
    XIcon,
    ArrowRightIcon
  },
  
  setup() {
    useHead({
      title: 'Results & Case Studies | N15 Labs Stoke-on-Trent',
      meta: [
        {
          name: 'description',
          content: 'Real results for real businesses. See how I\'ve helped local companies reduce Google Ads costs by 75%, increase organic traffic by 110%, and generate 618+ conversions.'
        },
        {
          property: 'og:title',
          content: 'Results & Case Studies | N15 Labs'
        },
        {
          property: 'og:description',
          content: 'Real results for real businesses. Google Ads, SEO, and web design case studies from Stoke-on-Trent.'
        },
        {
          name: 'keywords',
          content: 'case studies, Google Ads results, SEO case study, web design portfolio, digital marketing results, Stoke-on-Trent'
        }
      ],
      link: [
        {
          rel: 'canonical',
          href: 'https://n15labs.co.uk/case-studies'
        }
      ]
    })
  },
  
  data() {
    return {
      // Project images
      sneaktrackImages: [
        require('@/assets/webp/sneaktrack-image.webp'),
        require('@/assets/webp/sneaktrack-image2.webp'),
        require('@/assets/webp/sneaktrack-image3.webp'),
        require('@/assets/webp/sneaktrack-image4.webp')
      ],
      keywordImages: [
        require('@/assets/webp/keyword.webp'),
        require('@/assets/webp/keyword2.webp')
      ],
      salesTrackerImages: [
        require('@/assets/webp/sales-tracker.webp'),
        require('@/assets/webp/sales-tracker-code.webp')
      ],
      
      // Current indices
      sneaktrackIndex: 0,
      keywordIndex: 0,
      salesTrackerIndex: 0,
      
      // Video states
      sneaktrackVideoPlaying: false,
      salesTrackerVideoPlaying: false,
      
      // Modal state
      modalOpen: false,
      modalProject: null,
      modalIndex: 0
    }
  },
  
  computed: {
    currentModalImages() {
      switch (this.modalProject) {
        case 'sneaktrack':
          return this.sneaktrackImages
        case 'keyword':
          return this.keywordImages
        case 'salestracker':
          return this.salesTrackerImages
        default:
          return []
      }
    }
  },
  
  methods: {
    prevImage(project) {
      switch (project) {
        case 'sneaktrack':
          if (this.sneaktrackIndex > 0) this.sneaktrackIndex--
          break
        case 'keyword':
          if (this.keywordIndex > 0) this.keywordIndex--
          break
        case 'salestracker':
          if (this.salesTrackerIndex > 0) this.salesTrackerIndex--
          break
      }
    },
    
    nextImage(project) {
      switch (project) {
        case 'sneaktrack':
          if (this.sneaktrackIndex < this.sneaktrackImages.length - 1) this.sneaktrackIndex++
          break
        case 'keyword':
          if (this.keywordIndex < this.keywordImages.length - 1) this.keywordIndex++
          break
        case 'salestracker':
          if (this.salesTrackerIndex < this.salesTrackerImages.length - 1) this.salesTrackerIndex++
          break
      }
    },
    
    playVideo(project) {
      switch (project) {
        case 'sneaktrack':
          this.sneaktrackVideoPlaying = true
          break
        case 'salestracker':
          this.salesTrackerVideoPlaying = true
          break
      }
    },
    
    openModal(project, index) {
      this.modalProject = project
      this.modalIndex = index
      this.modalOpen = true
      document.body.style.overflow = 'hidden'
    },
    
    closeModal() {
      this.modalOpen = false
      this.modalProject = null
      this.modalIndex = 0
      document.body.style.overflow = ''
    },
    
    prevModalImage() {
      if (this.modalIndex > 0) this.modalIndex--
    },
    
    nextModalImage() {
      if (this.modalIndex < this.currentModalImages.length - 1) this.modalIndex++
    }
  },
  
  mounted() {
    // Handle escape key
    document.addEventListener('keydown', (e) => {
      if (e.key === 'Escape' && this.modalOpen) {
        this.closeModal()
      }
    })
  }
}
</script>

